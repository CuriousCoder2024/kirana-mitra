"""Shelf-scan eval: `uv run python -m tests.eval.shelf.run --base http://localhost:8090 [--set real]`.

Posts every labelled image to /shelf-scan and compares the returned counts with
the label file. Sets:
  synthetic (default): images/*.jpg generated by make_images.py, exact counts.
  real: real/labels.json, hand-counted photos under docs/design/assets/photos/
        (referenced by repo-relative "path", never copied here). Each labelled
        item may carry "tol" (count tolerance) and the file may list "maybe"
        products (identity uncertain: reported, not scored) and "unmatched"
        brands expected outside the catalogue.
Reports, per image and overall: detection recall (labelled products that came
back), precision (returned products that were labelled), exact-count rate
(within tolerance), mean absolute count error, and latency. Appends a row to
results.csv with the date, model and set.
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
import sys
import time
from datetime import datetime
from pathlib import Path

import httpx

HERE = Path(__file__).parent
REPO_ROOT = HERE.parents[3]


def _norm(s: str) -> str:
    return " ".join(s.lower().replace("-", " ").split())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://localhost:8090")
    ap.add_argument("--set", default="synthetic", choices=["synthetic", "real"])
    ap.add_argument("--labels", default=None)
    ap.add_argument("--results", default=str(HERE / "results.csv"))
    args = ap.parse_args(argv)

    labels_path = Path(args.labels) if args.labels else (
        HERE / "real" / "labels.json" if args.set == "real" else HERE / "labels.json")
    labels: dict = json.loads(labels_path.read_text(encoding="utf-8"))
    labels = {k: v for k, v in labels.items() if not k.startswith("_")}  # "_notes" etc.
    rows = []
    with httpx.Client(base_url=args.base, timeout=120) as c:
        model = c.get("/health").json().get("model", "?")
        shop_id = c.post("/shops", json={"shop_name": "Shelf Eval", "owner_name": "Eval",
                                         "language": "hi-Latn"}).json()["shop_id"]
        for fname, meta in labels.items():
            path = (REPO_ROOT / meta["path"]) if meta.get("path") else HERE / "images" / fname
            # counts may be ints (exact) or {"count": n, "tol": t}
            truth, tol = {}, {}
            for k, v in meta["counts"].items():
                if isinstance(v, dict):
                    truth[_norm(k)], tol[_norm(k)] = int(v["count"]), int(v.get("tol", 0))
                else:
                    truth[_norm(k)], tol[_norm(k)] = int(v), 0
            maybe = {_norm(k): v for k, v in (meta.get("maybe") or {}).items()}
            mime = "image/png" if path.suffix.lower() == ".png" else "image/jpeg"
            t0 = time.perf_counter()
            r = c.post("/shelf-scan", data={"shop_id": shop_id},
                       files={"image": (fname, path.read_bytes(), mime)})
            ms = (time.perf_counter() - t0) * 1000
            if r.status_code != 200:
                rows.append({"image": fname, "ok": False, "status": r.status_code, "ms": ms,
                             "truth": truth, "tol": tol, "maybe": maybe, "got": {}, "unmatched": [],
                             "reply": r.text[:200]})
                continue
            body = r.json()
            got = {}
            for it in body["items"]:
                got[_norm(it["name"])] = got.get(_norm(it["name"]), 0) + int(it["count"])
            rows.append({"image": fname, "ok": True, "status": 200, "ms": ms, "truth": truth,
                         "tol": tol, "maybe": maybe, "got": got,
                         "unmatched": [(u["name"], u["count"]) for u in body.get("unmatched", [])],
                         "reply": body["reply_text"]})

    # ---- scoring ----
    tp = fp = fn = 0
    exact = 0
    abs_errors: list[float] = []
    per_image = []
    for row in rows:
        truth, got, tol, maybe = row["truth"], row["got"], row["tol"], row["maybe"]
        detected = [k for k in truth if k in got]
        missed = [k for k in truth if k not in got]
        extra = [k for k in got if k not in truth and k not in maybe]  # "maybe" items are never penalised
        errs = [abs(got[k] - truth[k]) for k in detected]
        ex = sum(1 for k in detected if abs(got[k] - truth[k]) <= tol.get(k, 0))
        tp += len(detected); fn += len(missed); fp += len(extra)
        exact += ex
        abs_errors.extend(errs)
        per_image.append((row, detected, missed, extra, ex, errs))

    lat = sorted(r["ms"] for r in rows)
    p50 = statistics.median(lat) if lat else 0.0
    p95 = lat[min(len(lat) - 1, max(0, int(round(0.95 * len(lat))) - 1))] if lat else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    exact_rate = exact / tp if tp else 0.0
    mae = statistics.mean(abs_errors) if abs_errors else 0.0
    failures = sum(1 for r in rows if not r["ok"])

    print(f"\nmodel={model}  base={args.base}  set={args.set}  images={len(rows)}\n")
    for row, detected, missed, extra, ex, errs in per_image:
        print(f"{row['image']:22} {row['ms']:7.0f} ms  "
              f"detected {len(detected)}/{len(row['truth'])}  exact {ex}/{len(detected) or 0}  "
              f"MAE {statistics.mean(errs) if errs else 0:.2f}")
        for k in row["truth"]:
            t = row["tol"].get(k, 0)
            ok = k in row["got"] and abs(row["got"][k] - row["truth"][k]) <= t
            print(f"    {'✓' if ok else '✗'} {k:14} true {row['truth'][k]:3}"
                  f"{f' ±{t}' if t else '   '}  got {row['got'].get(k, '-'):>3}")
        for k, v in row["maybe"].items():
            print(f"    ? {k:14} maybe {v!s:>8}  got {row['got'].get(k, '-'):>3}  (not scored)")
        for k in extra:
            print(f"    + {k:14} extra        got {row['got'][k]:>3}")
        if row["unmatched"]:
            print(f"    unmatched: {', '.join(f'{n} {c}' for n, c in row['unmatched'][:8])}")
        if not row["ok"]:
            print(f"    HTTP {row['status']}: {row['reply']}")
    print()
    print(f"detection recall : {recall:6.1%}   ({tp}/{tp + fn} labelled products found)")
    print(f"precision        : {precision:6.1%}   ({fp} unexpected products)")
    print(f"exact-count rate : {exact_rate:6.1%}   ({exact}/{tp} detected products counted within tolerance)")
    print(f"count MAE        : {mae:6.2f} units")
    print(f"latency p50/p95  : {p50:6.0f} / {p95:.0f} ms")
    print(f"http failures    : {failures}")

    results = Path(args.results)
    new = not results.exists()
    with results.open("a", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        if new:
            w.writerow(["date", "model", "images", "recall", "precision", "exact_count_rate",
                        "count_mae", "p50_ms", "p95_ms", "http_failures", "set"])
        w.writerow([datetime.now().isoformat(timespec="seconds"), model, len(rows),
                    f"{recall:.3f}", f"{precision:.3f}", f"{exact_rate:.3f}", f"{mae:.2f}",
                    f"{p50:.0f}", f"{p95:.0f}", failures, args.set])
    print(f"\nappended to {results}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
